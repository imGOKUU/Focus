package com.meltide.app.presentation.screens

import androidx.compose.runtime.Composable
import androidx.compose.runtime.getValue
import androidx.compose.ui.Modifier
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.toArgb
import com.airbnb.lottie.LottieProperty
import com.airbnb.lottie.compose.LottieAnimation
import com.airbnb.lottie.compose.LottieCompositionSpec
import com.airbnb.lottie.compose.rememberLottieComposition
import com.airbnb.lottie.compose.rememberLottieDynamicProperties
import com.airbnb.lottie.compose.rememberLottieDynamicProperty
import com.meltide.app.R

/**
 * Progress-scrubbed can-in-ice animation backed by res/raw/melting_can.json
 * (generated by tools/generate_melting_can.py - re-run that script to tweak
 * ice timing or cube count, don't hand-edit the JSON).
 *
 * The JSON's own timeline runs forward in time (frame 0 = fully iced, frame
 * 100 = fully melted), but `progress` here follows this app's existing
 * convention of remaining-time-fraction (1 = session just started, 0 = time's
 * up/fully melted) - same direction the previous hand-drawn Canvas
 * illustration used - so it's inverted when scrubbing the composition.
 *
 * A session starting fully buried (frame 0) reads as "nothing has happened
 * yet" rather than "time is flowing" - [InitialIceFraction] skips straight to
 * the point in the timeline where the ice is already most of the way covered
 * (lid just starting to frost, per the asset's own staging) so there's
 * immediate visual texture at progress=1, while progress=0 still lands on
 * frame 100 (fully melted) exactly as before.
 */
private const val InitialIceFraction = 0.8f

@Composable
fun MeltingCanAnimation(
    progress: Float,
    canColor: Color,
    modifier: Modifier = Modifier
) {
    val composition by rememberLottieComposition(LottieCompositionSpec.RawRes(R.raw.melting_can))
    val dynamicProperties = rememberLottieDynamicProperties(
        rememberLottieDynamicProperty(
            property = LottieProperty.COLOR,
            value = canColor.toArgb(),
            keyPath = arrayOf("CanBody", "Accent", "AccentFill")
        ),
        rememberLottieDynamicProperty(
            property = LottieProperty.COLOR,
            value = canColor.toArgb(),
            keyPath = arrayOf("CanReflection", "Accent", "AccentFill")
        ),
    )
    LottieAnimation(
        composition = composition,
        progress = {
            val elapsed = 1f - progress.coerceIn(0f, 1f)
            ((1f - InitialIceFraction) + elapsed * InitialIceFraction).coerceIn(0f, 1f)
        },
        dynamicProperties = dynamicProperties,
        modifier = modifier
    )
}
